function article(sections: [string, string][]) {
  return {
    type: "doc",
    content: sections.flatMap(([title, text]) => [
      {
        type: "heading",
        attrs: { level: 2 },
        content: [{ type: "text", text: title }],
      },
      { type: "paragraph", content: [{ type: "text", text }] },
    ]),
  };
}

