import { createHash } from "node:crypto";
import { defaultSettings } from "./cms.defaults";
import type { RichNode } from "./cms.entities";

/** Source-managed documents: the administration interface only edits contacts. */
export function privacyDocuments(contacts: Record<string, unknown>) {
  const email = String(contacts.email || defaultSettings.email);
  const operator = `${defaultSettings.legalName}, ИНН ${defaultSettings.inn}, ОГРНИП ${defaultSettings.egrip}, адрес: ${defaultSettings.legalAddress}`;
  const paragraph = (text: string): RichNode => ({
    type: "paragraph",
    content: [{ type: "text", text }],
  });
  const document = (sections: [string, string][]): RichNode => ({
    type: "doc",
    content: sections.flatMap(([title, text]) => [
      {
        type: "heading",
        attrs: { level: 2 },
        content: [{ type: "text", text: title }],
      },
      paragraph(text),
    ]),
  });
  const privacyBody = document([
    [
      "1. Оператор и область действия",
      `Редакция от 13 октября 2026 года. Оператор персональных данных сайта «ВИДЕОХРАНИТЕЛЬ»: ${operator}. Обращения по вопросам обработки данных принимаются по адресу ${email}. Политика относится к заявкам на консультацию, подбор оборудования, расчёт стоимости и выполнение работ, направленным через сайт.`,
    ],
    [
      "2. Какие данные обрабатываются",
      "При отправке заявки обрабатываются указанные вами имя и телефон, а также сообщение, если вы его заполнили. Сохраняются страница обращения, дата и время согласия, редакция согласия и идентификатор заявки. Для защиты формы от злоупотреблений используются технические сведения о запросе и необратимые контрольные значения IP-адреса и телефона. Не указывайте в сообщении паспортные данные, сведения о здоровье и данные третьих лиц.",
    ],
    [
      "3. Цели и основания",
      "Данные заявки нужны, чтобы связаться с вами, ответить на вопросы, уточнить объект и состав работ, подготовить предложение и согласовать дальнейшие действия. Основание — ваше отдельное согласие на обработку персональных данных. При заключении договора обработка необходимых для него данных также осуществляется на основании договора и требований законодательства Российской Федерации, включая Федеральный закон № 152-ФЗ «О персональных данных». Согласие на заявку не является согласием на рекламные рассылки.",
    ],
    [
      "4. Порядок обработки и доступ",
      "Обработка может включать сбор, запись, систематизацию, накопление, хранение, уточнение, извлечение, использование, предоставление доступа уполномоченным лицам оператора, блокирование, удаление и уничтожение с использованием средств автоматизации и без них. Заявки доступны оператору через защищённую административную часть сайта. Данные не публикуются для неограниченного круга лиц и не продаются. Привлечение технических исполнителей допускается только при наличии законного основания и обязательств по конфиденциальности и защите данных. Передача государственным органам возможна в случаях, установленных законом.",
    ],
    [
      "5. Срок хранения и прекращение обработки",
      "Данные хранятся до достижения цели обращения или отзыва согласия, если отсутствует другое законное основание для продолжения обработки. После достижения цели либо получения отзыва оператор прекращает обработку и уничтожает данные в сроки, предусмотренные законодательством. Документы, необходимые для исполнения договора и обязательного хранения по закону, сохраняются на соответствующем законном основании.",
    ],
    [
      "6. Права и обращения",
      `Вы вправе запросить сведения об обработке, потребовать уточнения, блокирования или уничтожения данных в предусмотренных законом случаях, отозвать согласие и обжаловать действия оператора в Роскомнадзоре или суде. Направьте обращение на ${email} или по адресу оператора. Для поиска заявки укажите телефон и дату обращения; оператор вправе запросить сведения, необходимые для подтверждения вашей личности. Отзыв согласия не отменяет законность обработки, выполненной до его получения.`,
    ],
    [
      "7. Защита и технические средства",
      "Оператор ограничивает доступ к заявкам, использует авторизацию административной части и меры защиты формы от повторных и автоматизированных запросов. Технические файлы браузера могут использоваться для сохранения темы оформления и работы защищённой сессии администратора. При переходе по ссылкам на внешние сайты, карты и мессенджеры действуют правила соответствующих сервисов. Не передавайте через форму секретные сведения.",
    ],
    [
      "8. Актуальная редакция",
      "Актуальная политика размещается на странице /privacy, отдельное согласие — на странице /consent. При изменении документов форма использует новую редакцию; вместе с каждой принятой заявкой сохраняется текст предоставленного согласия и его версия.",
    ],
    [
      "9. Статистика посещений",
      "На сайте используется Яндекс Метрика — сервис ООО «ЯНДЕКС» для статистики посещений. Сервис может обрабатывать технические сведения о браузере и устройстве, IP-адрес, адреса посещённых страниц, источник перехода и cookie. Эти сведения используются для оценки работы сайта. Запись действий внутри формы через Вебвизор отключена; имя, телефон и сообщение заявки не передаются в события статистики. Настройки браузера позволяют ограничивать cookie и блокировать загрузку внешних сервисов. Условия сервиса доступны на сайте Яндекса.",
    ],
  ]);
  const consentText = `Даю ${defaultSettings.legalName} согласие на обработку моих персональных данных для ответа на заявку.`;
  const consentBody = document([
    [
      "Согласие на обработку персональных данных",
      `Редакция от 13 октября 2026 года. Я свободно, своей волей и в своём интересе даю оператору ${operator} согласие на обработку указанных мной в форме имени, телефона и сообщения, а также страницы обращения, даты и времени согласия, его редакции и идентификатора заявки. Цели: ответ на обращение, консультация, подбор оборудования, расчёт стоимости и согласование работ.`,
    ],
    [
      "Действия с данными",
      "Согласие распространяется на сбор, запись, систематизацию, накопление, хранение, уточнение, извлечение, использование, предоставление доступа уполномоченным лицам оператора, блокирование, удаление и уничтожение данных с использованием средств автоматизации и без них. Оно не разрешает публикацию данных для неограниченного круга лиц и рекламные рассылки.",
    ],
    [
      "Срок действия и отзыв",
      `Согласие действует до достижения цели обращения или его отзыва. Отозвать согласие можно письмом на ${email} или по почтовому адресу оператора с указанием сведений, позволяющих найти заявку и подтвердить личность заявителя. При отсутствии иного законного основания оператор прекращает обработку и уничтожает данные в предусмотренные законом сроки.`,
    ],
    [
      "Как предоставляется согласие",
      "Согласие предоставляется отдельно от политики: отметкой незаполненного заранее поля согласия и отправкой формы заявки. Текст согласия и его редакция сохраняются с заявкой. Ознакомиться с порядком обработки данных можно на странице /privacy.",
    ],
  ]);
  const hex = createHash("sha256")
    .update(JSON.stringify({ privacyBody, consentBody, consentText }))
    .digest("hex");
  const policyVersion = `${hex.slice(0, 8)}-${hex.slice(8, 12)}-4${hex.slice(13, 16)}-8${hex.slice(17, 20)}-${hex.slice(20, 32)}`;
  return {
    privacyPublished: true,
    privacyBody,
    consentBody,
    consentText,
    policyVersion,
  };
}
